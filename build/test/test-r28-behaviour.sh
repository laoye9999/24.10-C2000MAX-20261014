#!/bin/sh
# Behaviour tests for the r28 fixes that cannot be settled by reading the code.
#
# Runs ON the device, because these are all questions about how the shipped
# scripts behave against a live system -- what a gate does when sing-box is
# running but the port is not, whether a restart actually happened.
#
#     scp test/test-r28-behaviour.sh root@192.168.66.1:/tmp/
#     ssh root@192.168.66.1 'sh /tmp/test-r28-behaviour.sh'
#
# Nothing here touches the live rules or the live rule sets. The hotplug hook is
# driven against a fake firewall.sh and a fake logger, and the refresher against
# a sandbox DIR under /tmp. Each variant is generated from the *installed* file
# by sed, and the negative controls are generated by removing the fix, so a test
# that would pass either way shows up as a pass in both directions and fails the
# assertion that expects them to differ.

set -u

SB=/tmp/hpr28beh.$$
PASS=0
FAIL=0

cleanup() {
	[ -n "${LOCKED:-}" ] && rm -rf /var/run/homeproxy-subscribe.lock
	rm -rf "$SB"
}
trap cleanup EXIT

# Refuse to run while an import is actually in flight: this test owns the
# subscribe lock file. Scanned through /proc rather than `pgrep -f`, which
# matches the shell running this very script.
for p in /proc/[0-9]*; do
	c=$(tr '\0' ' ' < "$p/cmdline" 2>/dev/null) || continue
	case "$c" in
		*subscribe.lua*) [ "$(basename "$p")" = "$$" ] || {
			echo "an import is running ($(basename "$p")); not starting" >&2
			exit 2
		} ;;
	esac
done

mkdir -p "$SB/bin" "$SB/work" "$SB/mirror/geoip" "$SB/mirror/geosite"

expect() {
	if [ "$2" = "$3" ]; then
		PASS=$((PASS + 1))
		printf '    ok    %s\n' "$1"
	else
		FAIL=$((FAIL + 1))
		printf '    FAIL  %s\n' "$1"
		printf '          expected [%s], got [%s]\n' "$2" "$3"
	fi
}

# ------------------------------------------------------------------- fakes

cat > "$SB/bin/logger" <<'EOF'
#!/bin/sh
echo "$*" >> /tmp/__SB__/log
EOF
sed -i "s|/tmp/__SB__|$SB|" "$SB/bin/logger"

cat > "$SB/bin/firewall.sh" <<'EOF'
#!/bin/sh
echo "firewall:$1" >> /tmp/__SB__/calls
case "$1" in
	check) exit 1 ;;   # the rules are gone, as after the vendor's eqos flush
	up|down) exit 0 ;;
esac
exit 2
EOF
sed -i "s|/tmp/__SB__|$SB|" "$SB/bin/firewall.sh"

chmod +x "$SB/bin"/*

HOOK=/etc/hotplug.d/iface/99-homeproxy
REFRESHER=/usr/share/homeproxy/update-rule-sets.sh

hook_variant() {
	# $1 out  $2 gate: "port:<n>" or "pidof"
	out=$1
	gate=$2
	set -- $(echo "$gate" | tr ':' ' ')
	if [ "$1" = "port" ]; then
		sed -e "s|/usr/share/homeproxy/firewall.sh|$SB/bin/firewall.sh|g" \
		    -e 's|^if \[ -f "\$GUARD_PID" \].*|if false; then|' \
		    -e "s|^config_get port inbound tproxy_port 5330\$|port=$2|" \
		    "$HOOK"
	else
		sed -e "s|/usr/share/homeproxy/firewall.sh|$SB/bin/firewall.sh|g" \
		    -e 's|^if \[ -f "\$GUARD_PID" \].*|if false; then|' \
		    -e 's|^config_get port inbound tproxy_port 5330$||' \
		    -e 's#^netstat -lnt.*#pidof sing-box >/dev/null 2>\&1 || exit 0#' \
		    "$HOOK"
	fi > "$out"
}

run_hook() {
	: > "$SB/calls"
	: > "$SB/log"
	PATH="$SB/bin:$PATH" ACTION=ifup sh "$1" >/dev/null 2>&1
	echo "$(grep -c '^firewall:up' "$SB/calls" 2>/dev/null)"
}

# ========================================================== 1. the hook gate
#
# stop_service runs stop_guard (which removes guard.pid) and then firewall.sh
# down, and rc.common does not kill the service until stop_service returns. For
# that whole window sing-box is in the process table with the rules already
# gone, which is the state the world is put into here.

printf '\n  the hotplug hook, in the stop window\n'

PORT=$(uci -q get homeproxy.inbound.tproxy_port)
[ -n "$PORT" ] || PORT=5330

hook_variant "$SB/hook-dead-port.sh" "port:59999"
hook_variant "$SB/hook-live-port.sh" "port:$PORT"
hook_variant "$SB/hook-old-pidof.sh" "pidof"

# The premise of the whole test: sing-box must be up, or the old gate would
# refuse too and the comparison would say nothing.
expect "premise: sing-box is running, so the old gate would have passed" \
	"yes" "$(pidof sing-box >/dev/null 2>&1 && echo yes || echo no)"
expect "premise: the port the new gate is pointed at is not listening" \
	"0" "$(netstat -lnt 2>/dev/null | grep -c ':59999 ')"

expect "a dead proxy port: the rules are NOT reinstalled" \
	"0" "$(run_hook "$SB/hook-dead-port.sh")"
expect "and nothing is logged about it" \
	"0" "$(grep -c 'reinstalling' "$SB/log" 2>/dev/null)"

# Without this the test above would also pass a script that simply always exits.
expect "control: with the port genuinely up, the rules ARE reinstalled" \
	"1" "$(run_hook "$SB/hook-live-port.sh")"

# And this is what the r28 change is worth.
expect "control: the pre-r28 gate reinstalls them in front of the dead port" \
	"1" "$(run_hook "$SB/hook-old-pidof.sh")"

# ================================================== 2. the rule-set throttle

printf '\n  the rule-set refresher\n'

refresher_variant() {
	# $1 out  $2 first mirror  $3 second mirror
	sed -e "s|^DIR=/etc/homeproxy/rule_set\$|DIR=$SB/ruleset|" \
	    -e "s|^STAMP=/etc/homeproxy/rule_set.stamp\$|STAMP=$SB/stamp|" \
	    -e "s|^exec 9>/var/run/homeproxy-ruleset.lock|exec 9>$SB/rs.lock|" \
	    -e "s|^MIRRORS=\".*|MIRRORS=\"$2|" \
	    -e "s|^https://gcore.*|$3\"|" \
	    "$REFRESHER" > "$1"
}

HAVE_SETS=0
mkdir -p "$SB/ruleset"
for f in geoip-cn geosite-cn 'geosite-geolocation-!cn'; do
	if [ -f "/etc/homeproxy/rule_set/$f.srs" ]; then
		cp "/etc/homeproxy/rule_set/$f.srs" "$SB/ruleset/$f.srs"
		HAVE_SETS=$((HAVE_SETS + 1))
	fi
done

if [ "$HAVE_SETS" -lt 3 ]; then
	printf '    skip  the local rule sets are missing, cannot test the refresher\n'
else
	# Mirror tree laid out the way the script builds its URLs.
	cp /etc/homeproxy/rule_set/geoip-cn.srs "$SB/mirror/geoip/cn.srs"
	cp /etc/homeproxy/rule_set/geosite-cn.srs "$SB/mirror/geosite/cn.srs"
	cp '/etc/homeproxy/rule_set/geosite-geolocation-!cn.srs' \
	   "$SB/mirror/geosite/geolocation-!cn.srs"

	# --- every mirror fails ---
	refresher_variant "$SB/rs-dead.sh" "http://127.0.0.1:9/a" "http://127.0.0.1:9/b"
	rm -f "$SB/stamp"
	before=$(md5sum "$SB/ruleset/geoip-cn.srs" | cut -c1-8)
	: > "$SB/log"
	PATH="$SB/bin:$PATH" sh "$SB/rs-dead.sh" --force >/dev/null 2>&1

	expect "every mirror failed: the throttle stamp is NOT advanced" \
		"no" "$([ -f "$SB/stamp" ] && echo yes || echo no)"
	expect "and the existing file is left alone" \
		"$before" "$(md5sum "$SB/ruleset/geoip-cn.srs" | cut -c1-8)"
	expect "and the refusal to advance is logged" \
		"1" "$(grep -c 'not advancing the rule-set throttle' "$SB/log" 2>/dev/null)"

	# --- a mirror that works, and files that genuinely differ ---
	refresher_variant "$SB/rs-ok.sh" "file://$SB/mirror" "file://$SB/nowhere"
	for f in geoip-cn geosite-cn 'geosite-geolocation-!cn'; do
		echo stale >> "$SB/ruleset/$f.srs"
	done
	rm -f "$SB/stamp"
	pid_before=$(pidof sing-box)
	up_before=$(cut -d' ' -f1 /proc/uptime | cut -d. -f1)
	: > "$SB/log"
	PATH="$SB/bin:$PATH" sh "$SB/rs-ok.sh" --force >/dev/null 2>&1
	pid_after=$(pidof sing-box)
	up_after=$(cut -d' ' -f1 /proc/uptime | cut -d. -f1)

	expect "a good run: the throttle stamp IS advanced" \
		"yes" "$([ -f "$SB/stamp" ] && echo yes || echo no)"
	expect "the changed rule set is swapped in" \
		"$(md5sum "$SB/mirror/geoip/cn.srs" | cut -c1-8)" \
		"$(md5sum "$SB/ruleset/geoip-cn.srs" | cut -c1-8)"
	expect "and the one that changed is logged as such" \
		"1" "$(grep -c 'rule sets changed' "$SB/log" 2>/dev/null)"

	# The point of the r28 change: a changed rule set must not bounce the
	# service. The pid is the direct evidence; uptime is the sanity check that
	# the box did not reboot underneath the test, which would have made a
	# changed pid mean nothing. Compared as "did not go backwards" rather than
	# for equality -- uptime ticks during the run.
	expect "the core was not restarted: same pid" "$pid_before" "$pid_after"
	if [ "$up_after" -ge "$up_before" ]; then
		expect "the box did not reboot mid-test" "1" "1"
	else
		expect "the box did not reboot mid-test" "$up_before" "$up_after"
	fi
fi

# ================================================= 3. the subscribe lock

printf '\n  the subscription import lock\n'

LOCK=/var/run/homeproxy-subscribe.lock
[ -d "$LOCK" ] && rm -rf "$LOCK"

sub_run() {
	PATH="$SB/bin:$PATH" lua /usr/lib/lua/homeproxy/subscribe.lua 2>&1
}

out=$(sub_run)
expect "no holder: the run proceeds" \
	"1" "$(echo "$out" | grep -c 'no subscriptions configured')"
expect "and it removes the lock on the way out" \
	"no" "$([ -d "$LOCK" ] && echo yes || echo no)"

mkdir -p "$LOCK"; echo 1 > "$LOCK/pid"; LOCKED=1
out=$(sub_run)
expect "held by a live pid: the run refuses" \
	"1" "$(echo "$out" | grep -c 'another update is already running')"
expect "and the live holder keeps its lock" \
	"yes" "$([ -d "$LOCK" ] && echo yes || echo no)"

echo 999999 > "$LOCK/pid"
out=$(sub_run)
expect "held by a dead pid: the run takes the lock over" \
	"1" "$(echo "$out" | grep -c 'no subscriptions configured')"
expect "and cleans it up afterwards" \
	"no" "$([ -d "$LOCK" ] && echo yes || echo no)"

mkdir -p "$LOCK"; rm -f "$LOCK/pid"; LOCKED=1
out=$(sub_run)
expect "held with no pid file yet: read as held, not stolen" \
	"1" "$(echo "$out" | grep -c 'another update is already running')"

rm -rf "$LOCK"; LOCKED=

printf '\n  %d passed, %d failed\n\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
